usage() {
    rule
    bold "v2.3 — тести ліпсинку на платі"
    echo
    echo "  0  чи то той сервер                     ./tools/lipsync-tests.sh 0"
    echo "  1  рот потрапляє в такт ⭐               ./tools/lipsync-tests.sh 1"
    echo "  2  кілька різних форм рота              ./tools/lipsync-tests.sh 2"
    echo "  3  обрив посеред відповіді              ./tools/lipsync-tests.sh 3"
    echo "  4  мікрофон після швидшої анімації      ./tools/lipsync-tests.sh 4"
    echo
    echo "  усі підряд                              ./tools/lipsync-tests.sh all"
    echo
    echo "  ⭐ тест 1 — це і є DoD фази: синхронність сприймається, а не рахується."
    echo
    echo "  Лог: $LOG"
    rule
}

main() {
    mkdir -p "$(dirname "$LOG")"
    case "${1:-}" in
        0) test_0 ;;
        1) test_0; test_1 ;;
        2) test_0; test_2 ;;
        3) test_0; test_3 ;;
        4) test_0; test_4 ;;
        all) test_0; test_1; test_2; test_3; test_4
             rule; bold "усі тести пройдено — надішліть $LOG"; rule ;;
        *) usage ;;
    esac
}

main "$@"
