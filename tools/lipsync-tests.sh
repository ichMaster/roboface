    echo "  Драбина має п'ять сходинок, і автотест доводить, що кожна досяжна — але на"
    echo "  синтетичному сигналі. Тут перевіряється, чи їх видно на реальному мовленні."
    echo
    echo "  **Не просимо говорити голосніше.** Перша версія цього тесту просила сказати те саме"
    echo "  тихо, потім голосно — і це неправильно за побудовою: синтез мови вирівнює гучність,"
    echo "  тож «голосно» дає майже той самий сигнал. Різниця, яку читає конверт, — це не"
    echo "  загальна гучність, а енергія у вікні 32 мс: довгі голосні проти проривних приголосних."
    echo "  Вона є в будь-якій фразі й не залежить від того, про що просити."
    echo
    echo "  Дивіться, чи рот відкривається на РІЗНУ величину протягом фрази."
    echo

    announce "Зараз я скажу довгу фразу. Дивіться, наскільки широко відкривається рот."
    watch_board 2 "різні форми" 45 \
        "Скажи повільно і виразно: оооо, ааа, потім швидко: тук-тук-тук, потім знову протяжно: уууу." \
        "дивіться на ширину рота"

    ask_choice 2 "Чи відкривався рот на РІЗНУ величину?" \
        "ТАК — на гучному помітно ширше, ніж на тихому" \
        "трохи різнилось, але ледве помітно" \
        "НІ — завжди однаково"
}

test_3() {
    header 3 "рот замовкає, коли замовкає звук"
    echo "  Третя знахідка рев'ю: конверт оновлювався лише коли черга віддавала звук"
    echo "  динаміку. Якщо мережа відставала посеред відповіді, рівень ЗАСТИГАВ — і рот"
    echo "  лишався в тій формі, у якій його застала затримка."
    echo
    echo "  Тест наводить саме таку затримку: сервер зупиняється ПОСЕРЕД відповіді."
    echo "  Дивіться на рот у момент, коли звук обірветься."
    echo

    announce "Зараз мене обірвуть посеред фрази. Дивіться на мій рот у цю мить."

    { echo; echo "=== ТЕСТ 3 — обрив посеред відповіді — $(date '+%H:%M:%S') ==="; } >> "$LOG"
    "$PY" "$ROOT/tools/board.py" --for 30 --log "$LOG" \
        --send "Порахуй уголос від одного до пʼятдесяти, повільно." --send-after 2 --send-when-idle \
        > /dev/null 2>&1 &
    local watcher=$!

    sleep 9
    echo "  ▸ обриваю сервер посеред відповіді"
    echo "[скрипт] тест 3 · remote.sh stop під час мовлення" >> "$LOG"
    "$ROOT/tools/remote.sh" stop > /dev/null 2>&1
    countdown 18 "дивіться на рот"
    wait "$watcher" 2>/dev/null

    echo "  ▸ піднімаю сервер"
    "$ROOT/tools/remote.sh" start 2>&1 | tail -1 | sed 's/^/    /'
    sleep 3

    ask_choice 3 "Що зробив рот, коли звук обірвався?" \
        "закрився невдовзі після того, як стих звук" \
        "лишився ВІДКРИТИМ і застиг у тій формі" \
        "продовжував рухатись без звуку" \
        "не помітив(ла)"
}

