#!/usr/bin/env bash
#
# v2.3 — ліпсинк на платі, по одному тесту за раз.
#
#     ./tools/lipsync-tests.sh 1     один тест
#     ./tools/lipsync-tests.sh all   усі підряд
#     ./tools/lipsync-tests.sh       список
#
# Автотести довели, що конверт правильно міряє енергію, що кожна форма рота досяжна, що жодна не
# займає більшості кадрів і що рівень спадає, коли звук припиняється — 317 тестів на хості. Чого
# вони не можуть сказати: **чи рот потрапляє в такт**. Синхронність сприймається, а не рахується.
#
# Тому питання тут — про очі й вуха разом. Скрипт сам говорить із платою; від вас потрібно дивитись
# на рот і слухати звук одночасно.
#
# Порт послідовного зв'язку тримає лише один процес: інші вікна `board.py` треба закрити.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PY="$ROOT/.venv/bin/python"
LOG="${RF_TEST_LOG:-$ROOT/lipsync-test.log}"

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
rule() { printf '────────────────────────────────────────────────────────\n'; }

countdown() {
    local seconds="$1" label="$2"
    for ((i = seconds; i > 0; i--)); do
        printf "\r  ▶ %s: %2d с  " "$label" "$i"
        sleep 1
    done
    printf "\r  ▶ %s: готово          \n" "$label"
}

announce() {
    local text="$1"
    echo "  🔊 (на платі) $text"
    echo "[скрипт] інструкція вголос: $text" >> "$LOG"
    "$PY" "$ROOT/tools/board.py" --for 12 --log "$LOG" \
        --send "Повтори дослівно, нічого не додаючи від себе: $text" --send-after 1 --send-when-idle \
        > /dev/null 2>&1
    sleep 1
}

watch_board() {
    local number="$1" title="$2" seconds="$3" command="$4" label="$5"
    { echo; echo "=== ТЕСТ $number — $title — $(date '+%Y-%m-%d %H:%M:%S') ==="; } >> "$LOG"

    local args=(--for "$seconds" --log "$LOG")
    [[ -n "$command" ]] && args+=(--send "$command" --send-after 2 --send-when-idle)

    local before; before=$(wc -l < "$LOG")
    "$PY" "$ROOT/tools/board.py" "${args[@]}" > /dev/null 2>&1 &
    local watcher=$!
    sleep 2
    countdown "$((seconds - 3))" "$label"
    wait "$watcher" 2>/dev/null

    echo
    bold "  що виміряла плата:"
    tail -n "+$((before + 1))" "$LOG" | grep -oE 'fps=[0-9]+ mic=[0-9]+|mouth=[0-9]+ lvl=[0-9-]+\.\.[0-9]+%|ref=[0-9]+ drop=[0-9]+' \
        | tail -6 | sed 's/^/    /'
    echo
}

ask_choice() {
    local number="$1" question="$2"; shift 2
    local options=("$@") answer="" count=${#options[@]}
    echo
    bold "  $question"
    for ((i = 0; i < count; i++)); do echo "    $((i + 1))) ${options[i]}"; done
    echo
    while [[ ! "$answer" =~ ^[0-9]+$ ]] || (( answer < 1 || answer > count )); do
        read -r -p "  Введіть число 1–$count: " answer
    done
    echo "[людина] тест $number · ${options[answer - 1]}" >> "$LOG"
    echo "  записано в лог: ${options[answer - 1]}"
    echo
}

header() { rule; bold "ТЕСТ $1 — $2"; echo; }

# --------------------------------------------------------------------------------------

test_0() {
    header 0 "чи то той сервер"
    local serving expected
    serving=$(curl -s -m 5 http://192.168.1.197:8000/openapi.json \
        | "$PY" -c "import sys,json;print(json.load(sys.stdin)['info']['version'])" 2>/dev/null)
    expected=$(cat "$ROOT/VERSION")
    echo "  сервер віддає: ${serving:-(не відповів)}"
    echo "  у репозиторії: $expected"
    echo "[скрипт] тест 0 · сервер=${serving:-none} репозиторій=$expected" >> "$LOG"
    if [[ "$serving" == "$expected" ]]; then
        bold "  ✅ збігається"
    else
        bold "  ❌ НЕ збігається — спочатку tools/remote.sh deploy && tools/remote.sh restart"
    fi
    echo
    echo "  Примітка: v2.3 не змінила серверного коду взагалі. Це єдина фаза, вміст якої"
    echo "  повністю на пристрої — але звірка лишається, бо вона дешева й одного разу вже"
    echo "  зекономила б годину."
    echo
}

test_1() {
    header 1 "рот потрапляє в такт"
    echo "  **Головний тест фази, і єдиний спосіб перевірити її DoD.**"
    echo
    echo "  Лічба дає рівні паузи між словами — саме на них рот має закриватись і знову"
    echo "  відкриватись. Дивіться на рот і слухайте одночасно: питання не в тому, чи рот"
    echo "  рухається (це вже доведено), а в тому, чи він рухається **разом зі звуком**."
    echo

    announce "Зараз я рахуватиму. Дивіться на мій рот і слухайте одночасно."
    watch_board 1 "синхронність" 50 \
        "Порахуй уголос від одного до двадцяти, повільно і чітко, через кому." \
        "дивіться на рот і слухайте"

    ask_choice 1 "Чи рухався рот РАЗОМ зі звуком?" \
        "ТАК — рот і звук збігались, рот закривався в паузах між числами" \
        "рот рухався, але помітно ВІДСТАВАВ від звуку" \
        "рот рухався, але ВИПЕРЕДЖАВ звук" \
        "рот рухався сам по собі, без зв'язку зі звуком" \
        "рот не рухався"

    ask_choice 1 "Чи закривався рот у паузах МІЖ числами?" \
        "ТАК — чітко закривався і знову відкривався" \
        "закривався не завжди" \
        "НІ — лишався відкритим усю лічбу"
}

test_2() {
