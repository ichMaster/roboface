        "ТАК — вираз помітно змінився на час паузи" \
        "ЧАСТКОВО — щось змінилось, але ледве" \
        "НІ — обличчя не змінювалось, поки він думав"
}

test_5() {
    header 5 "обрив зв'язку — і обличчя лишається offline"
    echo "  Рев'ю знайшло друге: ttl останнього серверного кадру продовжував іти після того, як"
    echo "  пристрій забирав обличчя собі. Через 8–60 секунд обличчя тихо ставало нейтральним"
    echo "  і починало кліпати — над пристроєм, який досі offline, поруч із індикатором аварії."
    echo
    echo "  Скрипт зупинить сервер, зачекає ХВИЛИНУ і підніме назад."
    echo "  Дивіться на обличчя ВЕСЬ цей час."
    echo

    announce "Зараз я втрачу зв'язок із сервером. Дивіться на обличчя цілу хвилину."

    echo "  ▸ зупиняю сервер"
    echo "[скрипт] тест 5 · remote.sh stop" >> "$LOG"
    "$ROOT/tools/remote.sh" stop 2>&1 | tail -2 | sed 's/^/    /'

    watch_board 5 "хвилина без сервера" 70 "" "дивіться на обличчя"

    echo "  ▸ піднімаю сервер"
    "$ROOT/tools/remote.sh" start 2>&1 | tail -2 | sed 's/^/    /'
    sleep 3

    ask_choice 5 "Яким було обличчя ВСЮ хвилину без сервера?" \
        "весь час однакове — сумне й пригашене (offline)" \
        "спершу offline, потім тихо стало звичайним і почало кліпати" \
        "одразу звичайне, ніби нічого не сталось" \
        "щось інше"

    ask_choice 5 "Чи повернулось обличчя до нормального ПІСЛЯ підняття сервера?" \
        "ТАК — повернулось саме" \
        "НІ — лишилось offline" \
        "не дочекався(лась)"
}

