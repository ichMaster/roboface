test_0() {
    header 0 "чи то взагалі той сервер"
    echo "  Найперше й найдешевше. Плата дзвонить на 192.168.1.197, і v2.2 працює тільки якщо"
    echo "  там справді свіжий сервер. Один раз це вже коштувало годину пошуку неіснуючого"
    echo "  баґа в прошивці."
    echo
    local serving
    serving=$(curl -s -m 5 http://192.168.1.197:8000/openapi.json \
        | "$PY" -c "import sys,json;print(json.load(sys.stdin)['info']['version'])" 2>/dev/null)
    local expected
    expected=$(cat "$ROOT/VERSION")

    echo "  сервер віддає: ${serving:-(не відповів)}"
    echo "  у репозиторії: $expected"
    echo "[скрипт] тест 0 · сервер=${serving:-none} репозиторій=$expected" >> "$LOG"

    if [[ "$serving" == "$expected" ]]; then
        bold "  ✅ збігається — можна тестувати далі"
    else
        bold "  ❌ НЕ збігається. Спочатку: tools/remote.sh deploy && tools/remote.sh restart"
        echo "     Без цього решта тестів перевіряє чужий код."
    fi
    echo
}

test_1() {
    header 1 "обличчя слідує за змістом відповіді"
    echo "  Суть фази: вираз обирає **сервер**, з того, що модель сама сказала про свій стан."
    echo "  Три запитання, три різні настрої. Дивіться на екран."
    echo

    announce "Зараз я тричі відповім. Дивіться на моє обличчя."

    for pair in "Розкажи щось радісне, одне речення.|радісне" \
                "Розкажи щось сумне, одне речення.|сумне" \
                "Порахуй у думці двадцять сім на вісімнадцять і скажи результат.|обчислення"; do
        local ask="${pair%%|*}" what="${pair##*|}"
        echo "  ▸ $what"
        watch_board 1 "обличчя за змістом ($what)" 22 "$ask" "дивіться на обличчя"
    done

    ask_choice 1 "Чи були три вирази обличчя ПОМІТНО різні?" \
        "ТАК — три різні вирази, і вони пасували до сказаного" \
        "ЧАСТКОВО — вирази різні, але не пасували до змісту" \
        "ЧАСТКОВО — змінювалось, але майже непомітно" \
        "НІ — обличчя весь час однакове"
}

test_2() {
    header 2 "рот рухається ВСЮ відповідь, і обличчя не пливе посеред речення"
    echo "  **Найважливіший тест фази.** Рев'ю знайшло, що кадр «розслабся» від сервера приходить,"
    echo "  поки плата ще договорює — і рот замикався, а дихання поверталось на середині речення."
    echo "  Це те саме, що ви ловили руками до v2.1.2. Виправлення є, але доведене лише чистим"
    echo "  тестом: чи справді рот живий до останнього слова, видно тільки звідси."
    echo
    echo "  Відповідь буде довга. Дивіться на рот **до самого кінця звуку**."
    echo

    # **Рахунок, а не розповідь.** Перша версія просила "історію Марса на десять речень" і
    # діставала відмову: системний промпт велить відповідати одним-двома реченнями, і модель
    # чесно про це казала. Звук усе одно виходив довгий, тож тест працював — випадково.
    #
    # Лічба довга за побудовою і не сперечається з персоною: це не відповідь, яку треба стискати.
    # Вона ще й дає рівні паузи між словами, а пауза — це саме те, на чому рот має закриватись
    # і знову відкриватись, тобто найкращий можливий сигнал для ока.
    announce "Зараз я буду рахувати. Дивіться на мій рот до останнього числа."
    watch_board 2 "довга відповідь" 55 \
        "Порахуй уголос від одного до тридцяти, повільно і чітко, через кому." \
        "дивіться на рот"

    ask_choice 2 "Що робив РОТ протягом усієї відповіді?" \
        "рухався від першого слова до останнього" \
        "рухався, але завмер десь посередині й далі стояв" \
        "рухався лише на початку" \
        "не рухався взагалі"

    ask_choice 2 "Чи починало обличчя ДИХАТИ або плавати, поки звук ще йшов?" \
        "НІ — обличчя було спокійне, рухався тільки рот" \
        "ТАК — дихання й дрейф повернулись, поки він ще говорив" \
        "не помітив(ла)"
}

