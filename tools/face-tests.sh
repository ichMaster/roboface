#!/usr/bin/env bash
#
# v2.2 — обличчя на платі, по одному тесту за раз.
#
#     ./tools/face-tests.sh 1     один тест
#     ./tools/face-tests.sh all   усі п'ять підряд
#     ./tools/face-tests.sh       список тестів
#
# Тут перевіряється те єдине, чого не доведе жоден лог: **як обличчя виглядає**. Автотести вже
# довели, що кадр правильно збирається, їде по проводу, розбирається на платі й дає правильний
# рецепт — 688 серверних і 297 на хості. Чого вони не можуть сказати: чи змінюється вираз тоді,
# коли треба, і чи не завмирає рот посеред речення.
#
# Тому питання тут — про очі, а не про числа. Скрипт сам подає команди платі й сам ставить питання;
# від вас потрібно дивитися на екран і відповідати. Усе лягає в один лог.
#
# Порт послідовного зв'язку тримає лише один процес: інші вікна `board.py` треба закрити.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PY="$ROOT/.venv/bin/python"
LOG="${RF_TEST_LOG:-$ROOT/face-test.log}"

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
rule() { printf '────────────────────────────────────────────────────────\n'; }

countdown() {
    local seconds="$1" label="$2"
    for ((i = seconds; i > 0; i--)); do
        printf "\r  ▶ %s: %2d с  " "$label" "$i"
        sleep 1
    done
    printf "\r  ▶ %s: готово          \n" "$label"
}

# Інструкцію промовляє **сама плата**, як у v1.4: якщо ви її почули, то зв'язок, синтез і динамік
# справні, і перевіряти їх окремо вже не треба.
announce() {
    local text="$1"
    echo "  🔊 (на платі) $text"
    echo "[скрипт] інструкція вголос: $text" >> "$LOG"
    "$PY" "$ROOT/tools/board.py" --for 12 --log "$LOG" \
        --send "Повтори дослівно, нічого не додаючи від себе: $text" --send-after 1 --send-when-idle \
        > /dev/null 2>&1
    sleep 1
}

# Заголовок у лог, board.py у фоні, відлік для людини, потім рядки саме цього тесту.
watch_board() {
    local number="$1" title="$2" seconds="$3" command="$4" label="$5"
    {
        echo
        echo "=== ТЕСТ $number — $title — $(date '+%Y-%m-%d %H:%M:%S') ==="
    } >> "$LOG"

    local args=(--for "$seconds" --log "$LOG")
    [[ -n "$command" ]] && args+=(--send "$command" --send-after 2 --send-when-idle)

    local before
    before=$(wc -l < "$LOG")

    "$PY" "$ROOT/tools/board.py" "${args[@]}" > /dev/null 2>&1 &
    local watcher=$!
    sleep 2
    countdown "$((seconds - 3))" "$label"
    wait "$watcher" 2>/dev/null

    echo
    bold "  що сказала плата:"
    tail -n "+$((before + 1))" "$LOG" \
        | grep -E '\[face\]|\[state\]|\[ws\]' | tail -8 | sed 's/^/    /'
    echo
}

# Питання з варіантами, відповідь — у той самий лог. Те, що бачить людина, інакше довелося б
# переказувати окремим повідомленням, і воно губилося б між тестами.
ask_choice() {
    local number="$1" question="$2"; shift 2
    local options=("$@") answer="" count=${#options[@]}

    echo
    bold "  $question"
    for ((i = 0; i < count; i++)); do
        echo "    $((i + 1))) ${options[i]}"
    done
    echo
    while [[ ! "$answer" =~ ^[0-9]+$ ]] || (( answer < 1 || answer > count )); do
        read -r -p "  Введіть число 1–$count: " answer
    done
    echo "[людина] тест $number · ${options[answer - 1]}" >> "$LOG"
    echo "  записано в лог: ${options[answer - 1]}"
    echo
}

header() {
    rule
    bold "ТЕСТ $1 — $2"
    echo
}

