usage() {
    rule
    bold "v2.2 — тести обличчя на платі"
    echo
    echo "  0  чи то взагалі той сервер            ./tools/face-tests.sh 0"
    echo "  1  обличчя слідує за змістом            ./tools/face-tests.sh 1"
    echo "  2  рот живий усю відповідь ⭐            ./tools/face-tests.sh 2"
    echo "  3  вираз змінюється перед словом         ./tools/face-tests.sh 3"
    echo "  4  «думаю» під час паузи                ./tools/face-tests.sh 4"
    echo "  5  обрив зв'язку                        ./tools/face-tests.sh 5"
    echo
    echo "  усі підряд                              ./tools/face-tests.sh all"
    echo
    echo "  ⭐ тест 2 найважливіший: це те, що ви вже ловили руками у v2.1."
    echo
    echo "  Лог: $LOG"
    rule
}

main() {
    mkdir -p "$(dirname "$LOG")"
    case "${1:-}" in
        0) test_0 ;;
        1) test_0; test_1 ;;
        2) test_0; test_2 ;;
        3) test_0; test_3 ;;
        4) test_0; test_4 ;;
        5) test_0; test_5 ;;
        all) test_0; test_1; test_2; test_3; test_4; test_5
             rule; bold "усі тести пройдено — надішліть $LOG"; rule ;;
        *) usage ;;
    esac
}

main "$@"
